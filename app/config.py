import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Путь к локальным весам модели (скачиваются scripts/download_model.py)
MODEL_PATH = Path(os.getenv("OCR_MODEL_PATH", ROOT / "models" / "Qwen3-VL-8B-Instruct"))
# Квантизация: "4bit" (для GPU 8 ГБ), "8bit" или "none" (bf16, для GPU от 24 ГБ)
QUANT = os.getenv("OCR_QUANT", "4bit")
# DPI рендера страницы PDF
DPI = int(os.getenv("OCR_DPI", "300"))
# Страница масштабируется до этой ширины (px) и режется на полосы не больше MAX_PIXELS:
# мелкая рукопись читается заметно лучше в высоком разрешении
TILE_WIDTH = int(os.getenv("OCR_TILE_WIDTH", "1700"))
# Максимальный размер одного изображения, подаваемого в модель (пикселей); ограничен видеопамятью
MAX_PIXELS = int(os.getenv("OCR_MAX_PIXELS", str(1_200_000)))
# Максимум токенов ответа на одну полосу
MAX_NEW_TOKENS = int(os.getenv("OCR_MAX_NEW_TOKENS", "2048"))
# Штраф за повторы. В таблицах одинаковые значения («НИО Елин») повторяются из строки в строку,
# штраф > 1 заставляет модель их искажать, поэтому по умолчанию он выключен (1.0).
# От зацикливания защищает LoopStopper; при срабатывании полоса перегенерируется с RETRY-штрафом.
REPETITION_PENALTY = float(os.getenv("OCR_REPETITION_PENALTY", "1.0"))
RETRY_REPETITION_PENALTY = float(os.getenv("OCR_RETRY_REPETITION_PENALTY", "1.1"))

# Одновременные запросы. Каждая копия модели (реплика) обрабатывает одну страницу за раз;
# реплики раскладываются по GPU по кругу (cuda:0, cuda:1, ...). На одном GPU несколько реплик
# помещаются, если хватает VRAM: 8B в 4-bit — ~5,5 ГБ на реплику + ~1,5 ГБ на обработку.
REPLICAS = int(os.getenv("OCR_REPLICAS", "1"))
# Сколько запросов обрабатывается/ждёт одновременно; сверх лимита сервис отвечает 503
MAX_ACTIVE_REQUESTS = int(os.getenv("OCR_MAX_ACTIVE_REQUESTS", "16"))

# Логи: уровень (DEBUG — с сырыми ответами модели) и папка для logs/ocr.log
LOG_LEVEL = os.getenv("OCR_LOG_LEVEL", "INFO").upper()
LOG_DIR = Path(os.getenv("OCR_LOG_DIR", ROOT / "logs"))

